//! The deciders on the chart layer's vocabulary: five marks (bars, pie, time
//! series, heatmap, map), colour, zoom, emphasis. Every case in
//! `cases_layer.json`, every decider; scored against the expected answers and
//! applied to the chart state.
//!
//!     set -a; source <env>/.env; set +a
//!     cargo run --release -p lidar-decide --bin layer_eval

use std::collections::BTreeMap;
use std::sync::Arc;

use lidar_decide::deciders::{Decider, Jev, Llm, Rules};
use lidar_decide::layer::model::{Mark, Quarter, State};
use lidar_decide::layer::{data, pilot};
use lidar_decide::options::NotApplied;
use serde_json::{Map, Value};

type Error = Box<dyn std::error::Error>;

/// Below this confidence, Jev's decision counts as "no change".
const GATE: f64 = 0.5;

fn matches(expect: &Value, answers: &Map<String, Value>) -> bool {
    expect.as_object().unwrap().iter().all(|(k, v)| {
        let got = answers.get(k).and_then(Value::as_str).unwrap_or("");
        match v {
            Value::Array(options) => options.iter().any(|o| o.as_str() == Some(got)),
            v => v.as_str() == Some(got),
        }
    })
}

fn start(v: &Value) -> State {
    let mark = pilot::MARKS.iter().map(|m| m.0).find(|m| Some(m.id()) == v["mark"].as_str()).unwrap_or(Mark::Bars);
    let dataset = lidar_decide::layer::model::Dataset::ALL.iter().map(|d| d.0).find(|d| mark.fits(*d)).unwrap();
    let mut s = State::new(dataset);
    s.mark = mark;
    s.title = s.default_title();
    s.highlight = v["highlight"].as_bool().unwrap_or(false);
    s.zoom = match v["zoom"].as_str() {
        Some("north_east") => Some(Quarter::NorthEast),
        Some("north_west") => Some(Quarter::NorthWest),
        Some("south_east") => Some(Quarter::SouthEast),
        Some("south_west") => Some(Quarter::SouthWest),
        _ => None,
    };
    s
}

#[tokio::main]
async fn main() -> Result<(), Error> {
    let root = env!("CARGO_MANIFEST_DIR");
    let cases: Value = serde_json::from_str(&std::fs::read_to_string(format!("{root}/cases_layer.json"))?)?;
    let d = data::load().await?;
    let client = reqwest::Client::new();
    let deciders: Vec<Arc<dyn Decider>> = vec![
        Arc::new(Rules),
        Arc::new(Jev { model: "typesafe/jev-1.13", client: client.clone() }),
        Arc::new(Llm { model: "anthropic/claude-haiku-4.5", client }),
    ];
    let q = pilot::questions();
    let mut md = String::from(
        "# Decisions on the chart layer\n\nGenerated by `layer_eval` from `cases_layer.json`. \
         ✓ = matches the expected answers. *Applied* is what the chart state does with it.\n\n\
         | Case | Start | Instruction | Expected | Decider | Decision | Conf. | ✓ | Applied |\n|---|---|---|---|---|---|---|---|---|\n",
    );
    // decider -> (right, gated right, n, ms, cost)
    let mut tot: BTreeMap<&str, (usize, usize, usize, Vec<f64>, f64)> = BTreeMap::new();
    let mut per_mark: BTreeMap<(&str, String), (usize, usize)> = BTreeMap::new();
    for c in cases["cases"].as_array().unwrap() {
        let s = start(&c["start"]);
        let text = c["text"].as_str().unwrap();
        let obs = pilot::observation(&s, &d, text);
        let expect_no_change = c["expect"]["action"] == "no_change";
        let expected_mark = c["expect"]["mark"].as_str().map(String::from)
            .or_else(|| c["expect"]["mark"].as_array().map(|_| "bars/pie".into()));
        for dc in &deciders {
            let dec = dc.decide(&obs, &q).await.map_err(|e| format!("{} on {}: {e}", dc.name(), c["id"]))?;
            let ok = matches(&c["expect"], &dec.answers);
            let conf = dec.confidence.unwrap_or(1.0);
            let gated = if conf < GATE { expect_no_change } else { ok };
            let applied = match pilot::apply(&s, &dec.answers) {
                Err(NotApplied::NeedsText) => "needs free text".into(),
                Err(NotApplied::Unfit(m)) => format!("refused: {m}"),
                Ok(n) if n == s => "nothing to do".into(),
                Ok(n) => format!("→ {}{}{}", n.mark.id(),
                    n.zoom.map_or(String::new(), |z| format!(", zoom {z:?}")),
                    if n.highlight { ", emphasis" } else { "" }),
            };
            let e = tot.entry(dc.name()).or_default();
            e.0 += ok as usize;
            e.1 += gated as usize;
            e.2 += 1;
            if !dec.cached || dec.ms > 0.0 {
                e.3.push(dec.ms);
            }
            e.4 += dec.cost;
            if let Some(m) = &expected_mark {
                let p = per_mark.entry((dc.name(), m.clone())).or_default();
                p.0 += ok as usize;
                p.1 += 1;
            }
            md += &format!(
                "| {} | {} | {} | {} | {} | {} | {} | {} | {} |\n",
                c["id"].as_str().unwrap(),
                s.mark.id(),
                text,
                c["expect"].to_string().replace('|', "/"),
                dc.name(),
                pilot::short(&dec.answers),
                dec.confidence.map_or("–".into(), |c| format!("{c:.2}")),
                if ok { "✓" } else { "✗" },
                applied,
            );
        }
    }
    md += &format!(
        "\n## Summary\n\n| Decider | Right | With confidence < {GATE} → no change | Latency p50 | Cost |\n|---|---|---|---|---|\n"
    );
    for (name, (ok, gated, n, mut ms, cost)) in tot {
        ms.sort_by(f64::total_cmp);
        let p50 = if ms.is_empty() || name == "rules" { "–".into() } else { format!("{:.0} ms", ms[ms.len() / 2]) };
        let gated = if name == "jev" { format!("{gated}/{n}") } else { "–".into() };
        let cost = if name == "rules" { "–".into() } else { format!("${cost:.4}") };
        md += &format!("| {name} | {ok}/{n} | {gated} | {p50} | {cost} |\n");
    }
    md += "\n## Mark changes, by target\n\n| Decider | Target | Right |\n|---|---|---|\n";
    for ((name, m), (ok, n)) in per_mark {
        md += &format!("| {name} | {m} | {ok}/{n} |\n");
    }
    std::fs::write(format!("{root}/results/layer_decisions.md"), &md)?;
    std::fs::write(
        format!("{root}/results/cache_used_layer_eval.txt"),
        lidar_decide::deciders::used_cache().join("\n"),
    )?;
    println!("{}", md.split("## Summary").nth(1).unwrap());
    Ok(())
}
